import { fileURLToPath } from 'url';
import path from 'path';
import { writeFileSync, mkdirSync, existsSync } from 'fs';
import fetch from 'node-fetch';
import AdmZip from 'adm-zip';

async function PrinceSessionSavedCredentials(txt) {
  const __filename = fileURLToPath(import.meta.url);
  const __dirname = path.dirname(__filename);

  const isDropbox =
    typeof txt === 'string' &&
    txt.startsWith('Prince~') &&
    txt.includes('scl/fi/') &&
    txt.includes('?rlkey=');

  if (!isDropbox) {
    throw new Error('Invalid Session ID format.');
  }

  let dropboxCode = txt.replace('Prince~', '');
  dropboxCode = dropboxCode.replace(/[?&]dl=\\d+/g, '');

  const separator = dropboxCode.includes('?') ? '&' : '?';
  const dropboxUrl = `https://www.dropbox.com/${dropboxCode}${separator}dl=1`;

  const response = await fetch(dropboxUrl, {
    redirect: 'follow',
    headers: {
      'User-Agent': 'Mozilla/5.0'
    }
  });

  if (!response.ok) {
    throw new Error(`Session download failed: ${response.status} ${response.statusText}`);
  }

  const data = Buffer.from(await response.arrayBuffer());
  if (!data.length) throw new Error('Downloaded Session ID file is empty.');

  const sessionDir = path.resolve(__dirname, '..', 'sessions');
  mkdirSync(sessionDir, { recursive: true });

  // New Session IDs are ZIP archives containing creds.json and all
  // multi-file Signal/auth keys. Restore every file to preserve the session.
  const isZip = data.length >= 4 &&
    data[0] === 0x50 && data[1] === 0x4b;

  if (isZip) {
    const zip = new AdmZip(data);
    const entries = zip.getEntries();

    for (const entry of entries) {
      const entryName = entry.entryName.replace(/\\\\/g, '/');
      if (!entryName || entryName.startsWith('/') || /^[A-Za-z]:/.test(entryName)) {
        throw new Error('Unsafe path found in session archive.');
      }

      const destination = path.resolve(sessionDir, entryName);
      if (destination !== sessionDir && !destination.startsWith(sessionDir + path.sep)) {
        throw new Error('Unsafe path found in session archive.');
      }

      if (entry.isDirectory) {
        mkdirSync(destination, { recursive: true });
        continue;
      }

      mkdirSync(path.dirname(destination), { recursive: true });
      writeFileSync(destination, entry.getData());
    }

    const credsPath = path.join(sessionDir, 'creds.json');
    if (!existsSync(credsPath)) {
      throw new Error('Session archive does not contain creds.json.');
    }

    JSON.parse(await (await import('fs/promises')).readFile(credsPath, 'utf8'));

    const files = zip.getEntries().filter(entry => !entry.isDirectory);
    const hasSignalKeys = files.some(entry =>
      /^(session-|pre-key-|sender-key-|app-state-sync-key-|app-state-sync-version-)/.test(
        path.posix.basename(entry.entryName.replace(/\\\\/g, '/'))
      )
    );

    if (!hasSignalKeys) {
      console.warn(
        '⚠️ Session ZIP contains creds.json but no Signal key files. ' +
        'Generate a fresh complete Session ID using the updated pair command.'
      );
    }

    return {
      success: true,
      path: credsPath,
      legacy: !hasSignalKeys
    };
  }

  // Backward compatibility for old Session IDs generated by the previous
  // pair command. Those files contain creds.json only, not Signal key files.
  let parsedData;
  try {
    parsedData = JSON.parse(data.toString('utf8'));
  } catch {
    throw new Error('Session ID is neither a valid ZIP archive nor valid JSON.');
  }

  const credsPath = path.join(sessionDir, 'creds.json');
  writeFileSync(credsPath, JSON.stringify(parsedData, null, 2));

  console.warn(
    '⚠️ Legacy creds-only Session ID restored. It does not include Signal session keys.'
  );

  return {
    success: true,
    path: credsPath,
    legacy: true
  };
}

export default PrinceSessionSavedCredentials;
